test('escalation: no doctor reaction in 15 min → admins; 30 min → relatives', async () => {
  const admin = await t.createAdmin()
  const doc = await t.createDoctor()
  const p = await t.patientOf(doc)
  await t.api('POST', '/api/patients/me/relatives', { token: p.token, body: { name: 'Жена', phone: '+79005550010' } })
  const m = await t.api('POST', `/api/patients/${p.user.id}/measurements`, { token: p.token, body: { type: 'blood_pressure', value: { systolic: 200, diastolic: 120 } } })
  const alertId = m.body.alerts[0].id
  t.advance(10 * 60_000)
  assert.equal((await runJobs(t.ctx)).escalated, 0)
  t.advance(6 * 60_000)
  assert.equal((await runJobs(t.ctx)).escalated, 1)
  let n = t.outbox({ alert_id: alertId, kind: 'escalation' })
  assert.ok(n.some((x) => x.user_id === doc.user.id && x.channel === 'sms'))
  assert.ok(n.some((x) => x.user_id === admin.user.id))
  assert.equal(t.outbox({ alert_id: alertId, kind: 'emergency' }).length, 1, 'only the initial emergency SMS so far')
  assert.equal((await runJobs(t.ctx)).escalated, 0, 'idempotent')
  t.advance(15 * 60_000)
  await runJobs(t.ctx)
  assert.equal(t.outbox({ alert_id: alertId, kind: 'emergency' }).length, 2)
  assert.equal(t.ctx.db.prepare('SELECT escalation_level FROM alerts WHERE id = ?').get(alertId).escalation_level, 2)
  const feed = await t.api('GET', '/api/alerts?status=open', { token: doc.token })
  assert.equal(feed.body.items.find((a) => a.id === alertId).escalationLevel, 2)
})

