test('individual thresholds set by the doctor change classification', async () => {
  const doc = await t.createDoctor()
  const p = await t.patientOf(doc)
  const pid = p.user.id
  const before = await t.api('POST', `/api/patients/${pid}/measurements`, { token: p.token, body: { type: 'glucose', value: { glucose: 9 } } })
  assert.equal(before.body.severity, 'normal')
  assert.equal((await t.api('PUT', `/api/patients/${pid}/thresholds/glucose`, { token: p.token, body: { warnHigh: 8 } })).status, 403, 'patient cannot change thresholds')
  assert.equal((await t.api('PUT', `/api/patients/${pid}/thresholds/glucose`, { token: doc.token, body: { critLow: 5, warnLow: 4, warnHigh: 8, critHigh: 12 } })).status, 400, 'order is validated')
  const set = await t.api('PUT', `/api/patients/${pid}/thresholds/glucose`, { token: doc.token, body: { critLow: 3.5, warnLow: 4.5, warnHigh: 8, critHigh: 12 } })
  assert.equal(set.status, 200)
  assert.equal(set.body.custom, true)
  const after = await t.api('POST', `/api/patients/${pid}/measurements`, { token: p.token, body: { type: 'glucose', value: { glucose: 9 } } })
  assert.equal(after.body.severity, 'warning')
  const view = await t.api('GET', `/api/patients/${pid}/thresholds`, { token: p.token })
  assert.equal(view.body.thresholds.glucose.warnHigh, 8)
  const other = await t.createDoctor()
  assert.equal((await t.api('PUT', `/api/patients/${pid}/thresholds/glucose`, { token: other.token, body: { warnHigh: 9 } })).status, 403)
  const reset = await t.api('DELETE', `/api/patients/${pid}/thresholds/glucose`, { token: doc.token })
  assert.equal(reset.body.custom, false)
})

