test('normalization: mg/dL → mmol/L, ranges, systolic > diastolic', () => {
  assert.deepEqual(normalizeMeasurement('glucose', { glucose: 180, unit: 'mg/dL' }), { glucose: 10 })
  assert.deepEqual(normalizeMeasurement('glucose', { glucose: '5,6' }), { glucose: 5.6 })
  assert.throws(() => normalizeMeasurement('glucose', { glucose: 90 }), /валидацию/)
  assert.throws(() => normalizeMeasurement('blood_pressure', { systolic: 80, diastolic: 90 }), /валидацию/)
  assert.deepEqual(normalizeMeasurement('blood_pressure', { systolic: 120.4, diastolic: 80, pulse: 70 }), { systolic: 120, diastolic: 80, pulse: 70 })
  assert.deepEqual(normalizeMeasurement('peak_flow', { peak_flow: 410 }), { peak_flow: 410 })
  assert.throws(() => normalizeMeasurement('weight', {}), /Неизвестный/)
})

test('manual input of glucose, blood pressure and peak flow; history with summary; encrypted at rest', async () => {
  const p = await t.registerPatient({ conditions: ['diabetes_t2', 'hypertension', 'asthma'] })
  const id = p.user.id
  const g = await t.api('POST', `/api/patients/${id}/measurements`, { token: p.token, body: { type: 'glucose', value: { glucose: 6.1, context: 'fasting' } } })
  assert.equal(g.status, 201)
  assert.equal(g.body.severity, 'normal')
  t.advance(30 * 60_000)
  await t.api('POST', `/api/patients/${id}/measurements`, { token: p.token, body: { type: 'blood_pressure', value: { systolic: 130, diastolic: 85, pulse: 72 } } })
  await t.api('POST', `/api/patients/${id}/measurements`, { token: p.token, body: { type: 'peak_flow', value: { peak_flow: 420 } } })
  const bad = await t.api('POST', `/api/patients/${id}/measurements`, { token: p.token, body: { type: 'blood_pressure', value: { systolic: 'abc', diastolic: 80 } } })
  assert.equal(bad.status, 400)
  const hist = await t.api('GET', `/api/patients/${id}/measurements`, { token: p.token })
  assert.equal(hist.body.items.length, 3)
  assert.equal(hist.body.summary.glucose.count, 1)
  assert.equal(hist.body.summary.systolic.last, 130)
  const onlyBp = await t.api('GET', `/api/patients/${id}/measurements?type=blood_pressure`, { token: p.token })
  assert.equal(onlyBp.body.items.length, 1)
  const raw = t.ctx.db.prepare('SELECT value_enc FROM measurements WHERE patient_id = ?').all(id)
  assert.ok(raw.every((r) => r.value_enc.startsWith('v1.') && !r.value_enc.includes('130')))
})

