test('doctor dashboard: all patients prioritized by criticality; patient card', async () => {
  const doc = await t.createDoctor()
  const calm = await t.patientOf(doc, { fullName: 'Аааа Спокойный' })
  const crit = await t.patientOf(doc, { fullName: 'Яяяя Критический' })
  const warn = await t.patientOf(doc, { fullName: 'Мммм Предупреждение' })
  const stale = await t.patientOf(doc, { fullName: 'Бббб Без данных' })
  await t.api('POST', `/api/patients/${calm.user.id}/measurements`, { token: calm.token, body: { type: 'glucose', value: { glucose: 6 } } })
  await t.api('POST', `/api/patients/${warn.user.id}/measurements`, { token: warn.token, body: { type: 'glucose', value: { glucose: 11 } } })
  await t.api('POST', `/api/patients/${crit.user.id}/measurements`, { token: crit.token, body: { type: 'glucose', value: { glucose: 20 } } })
  const dash = await t.api('GET', '/api/doctor/dashboard', { token: doc.token })
  assert.equal(dash.status, 200)
  assert.deepEqual(dash.body.patients.map((x) => x.id), [crit.user.id, warn.user.id, stale.user.id, calm.user.id])
  assert.deepEqual(dash.body.totals, { patients: 4, critical: 1, warning: 1, stale: 1 })
  const card = await t.api('GET', `/api/patients/${crit.user.id}`, { token: doc.token })
  assert.equal(card.status, 200)
  assert.equal(card.body.summary30d.glucose.max, 20)
  assert.equal(card.body.alerts.length, 1)
  assert.ok(card.body.thresholds.glucose)
  const other = await t.createDoctor()
  assert.equal((await t.api('GET', `/api/patients/${crit.user.id}`, { token: other.token })).status, 403)
  const access = t.ctx.db.prepare('SELECT * FROM data_access_log WHERE user_id = ? AND patient_id = ?').all(doc.user.id, crit.user.id)
  assert.ok(access.some((a) => a.resource === 'card') && access.some((a) => a.resource === 'dashboard'))
})

