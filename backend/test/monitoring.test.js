test('critical value → alert, doctor push+SMS, patient push, relative emergency SMS', async () => {
  const doc = await t.createDoctor('Врач Алертов')
  const p = await t.patientOf(doc)
  await t.api('POST', '/api/patients/me/relatives', { token: p.token, body: { name: 'Сын', phone: '+79005550001', relation: 'сын' } })
  await t.api('POST', '/api/patients/me/relatives', { token: p.token, body: { name: 'Сосед', phone: '+79005550002', notifyEmergency: false } })
  const m = await t.api('POST', `/api/patients/${p.user.id}/measurements`, { token: p.token, body: { type: 'glucose', value: { glucose: 2.4 } } })
  assert.equal(m.body.severity, 'critical')
  assert.equal(m.body.alerts.length, 1)
  const alertId = m.body.alerts[0].id
  await t.flush()
  const n = t.outbox({ alert_id: alertId })
  assert.ok(n.some((x) => x.user_id === doc.user.id && x.channel === 'push'))
  assert.ok(n.some((x) => x.user_id === doc.user.id && x.channel === 'sms' && x.recipient === doc.user.phone))
  assert.ok(n.some((x) => x.user_id === p.user.id && x.channel === 'push'))
  assert.ok(n.some((x) => x.kind === 'emergency' && x.recipient === '+79005550001'))
  assert.ok(!n.some((x) => x.recipient === '+79005550002'), 'relative without emergency flag is not notified')
  assert.ok(n.every((x) => x.status === 'sent'))
  // The platform does not give medical advice to the patient.
  const patientMsg = n.find((x) => x.user_id === p.user.id)
  assert.match(patientMsg.body, /передана лечащему врачу/)

  const feed = await t.api('GET', '/api/alerts?status=open', { token: doc.token })
  assert.equal(feed.body.items[0].id, alertId)
  assert.equal(feed.body.items[0].measurement.value.glucose, 2.4)
  t.advance(4 * 60_000)
  const ack = await t.api('POST', `/api/alerts/${alertId}/ack`, { token: doc.token })
  assert.equal(ack.status, 200)
  assert.equal(ack.body.status, 'acknowledged')
  assert.equal(ack.body.reactionMinutes, 4)
  assert.equal((await t.api('POST', `/api/alerts/${alertId}/ack`, { token: doc.token })).status, 409)
  const resolved = await t.api('POST', `/api/alerts/${alertId}/resolve`, { token: doc.token, body: { note: 'Связался с пациентом' } })
  assert.equal(resolved.body.status, 'resolved')
})

